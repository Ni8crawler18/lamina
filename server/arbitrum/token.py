# ─── USDC coupon payments (replaces HBAR transfer) ───────────────────────────

def transfer_hbar(to_address: str, amount_tinybars: int) -> str:
    """Transfer USDC to a holder as coupon payment.

    API-compatible with the Hedera version (same function name, same params).
    amount_tinybars is reinterpreted as USDC micro-units (6 decimals).

    UPGRADE: Hedera paid coupons in HBAR (gas token).
             Robinhood Chain pays coupons in USDC — USD-denominated,
             exactly what institutional investors expect.
    """
    return transfer_usdc(to_address, amount_tinybars)


def transfer_usdc(to_address: str, amount_units: int) -> str:
    """Transfer USDC from operator to recipient. amount_units in USDC smallest unit (6 dec).

    Returns tx_hash.
    """
    settings = get_settings()
    if not settings.usdc_address:
        logger.warning("USDC_ADDRESS not configured — coupon payment skipped")
        return "usdc_not_configured"

    w3       = get_web3()
    operator = get_operator_address()
    pk       = get_operator_private_key()

    usdc = w3.eth.contract(
        address=Web3.to_checksum_address(settings.usdc_address),
        abi=_MINIMAL_ERC20_ABI,
    )

    tx = usdc.functions.transfer(
        Web3.to_checksum_address(to_address), amount_units
    ).build_transaction({
        "chainId":  settings.chain_id,
        "from":     Web3.to_checksum_address(operator),
        "nonce":    next_nonce(w3, operator),
        "gas":      100_000,
        "gasPrice": w3.eth.gas_price,
    })
    tx_hash = build_and_send(w3, tx, pk)
    logger.info(f"USDC coupon: {amount_units} units → {to_address}")
    return tx_hash


def get_token_balance(token_address: str, account_address: str) -> int:
    """Read ERC-20 balanceOf. Utility for balance sync."""
    token = _get_token_contract(token_address)
    return token.functions.balanceOf(
        Web3.to_checksum_address(account_address)
    ).call()

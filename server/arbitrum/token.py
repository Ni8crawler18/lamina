def transfer_tokens(
    token_address: str,
    from_address: str,
    to_address: str,
    amount: int,
    decimals: int = 2,
) -> str:
    """Transfer tokens from operator treasury to an investor. Returns tx_hash.

    The compliance hooks inside LaminaRWAToken._update() auto-enforce
    KYC and freeze state — no pre-flight check needed here.
    """
    w3       = get_web3()
    settings = get_settings()
    token    = _get_token_contract(token_address)
    operator = get_operator_address()
    pk       = get_operator_private_key()

    tx = token.functions.transfer(
        Web3.to_checksum_address(to_address), amount
    ).build_transaction({
        "chainId":  settings.chain_id,
        "from":     Web3.to_checksum_address(operator),   # must be treasury (from_address)
        "nonce":    next_nonce(w3, operator),
        "gas":      150_000,
        "gasPrice": w3.eth.gas_price,
    })
    tx_hash = build_and_send(w3, tx, pk)
    logger.info(f"Transferred {amount} of {token_address} → {to_address}")
    return tx_hash



from server.config import get_settings

logger = logging.getLogger(__name__)

# ─── ABI loading ─────────────────────────────────────────────────────────────
_ABI_DIR = Path(__file__).parent.parent.parent / "contracts" / "abi"

def _load_abi(name: str) -> list:
    """Load ABI from contracts/abi/<name>.json (generated by deploy script)."""
    path = _ABI_DIR / f"{name}.json"
    if not path.exists():
        raise FileNotFoundError(
            f"ABI file not found: {path}\n"
            "Run contracts/scripts/deploy.py first to compile and deploy contracts."
        )
    with open(path) as f:
        return json.load(f)


# Lazy-loaded contract instances
_factory_contract = None
_token_abi = None
_erc20_abi = None   # minimal ERC-20 ABI for USDC transfers


def _get_factory():
    global _factory_contract
    if _factory_contract is None:
        settings = get_settings()
        w3 = get_web3()
        _factory_contract = w3.eth.contract(
            address=Web3.to_checksum_address(settings.factory_address),
            abi=_load_abi("LaminaFactory"),
        )
    return _factory_contract


def _get_token_abi():
    global _token_abi
    if _token_abi is None:
        _token_abi = _load_abi("LaminaRWAToken")
    return _token_abi


def _get_token_contract(token_address: str):
    w3 = get_web3()
    return w3.eth.contract(
        address=Web3.to_checksum_address(token_address),
        abi=_get_token_abi(),
    )


_MINIMAL_ERC20_ABI = [
    {
        "inputs": [
            {"internalType": "address", "name": "to",     "type": "address"},
            {"internalType": "uint256", "name": "amount", "type": "uint256"},
        ],
        "name": "transfer",
        "outputs": [{"internalType": "bool", "name": "", "type": "bool"}],
        "stateMutability": "nonpayable",
        "type": "function",
    },
    {
        "inputs": [{"internalType": "address", "name": "account", "type": "address"}],
        "name": "balanceOf",
        "outputs": [{"internalType": "uint256", "name": "", "type": "uint256"}],
        "stateMutability": "view",
        "type": "function",
    },
]


# ─── Account ─────────────────────────────────────────────────────────────────

def create_account(initial_balance_hbar: int = 10) -> tuple[str, str]:
    """Generate a new ETH wallet keypair.

    The `initial_balance_hbar` param is kept for API compatibility with
    the Hedera version (it had meaning there; on EVM we ignore it — the
    operator can fund new wallets separately if needed).

    Returns (address, private_key_hex).
    """
    acct = Account.create()
    addr = acct.address
    key  = acct.key.hex()
    logger.info(f"Created EVM account: {addr}")
    return addr, key


# ─── Token deployment ─────────────────────────────────────────────────────────

def create_token(
    name: str,
    symbol: str,
    decimals: int = 2,
    initial_supply: int = 0,
    max_supply: int = 0,        # kept for API compat; ERC-20 has no built-in max
    asset_type: str = "bond",
    jurisdiction: str = "US",
) -> tuple[str, str]:
    """Deploy a new LaminaRWAToken via LaminaFactory.

    Returns (token_address, topic_id_hex) — the audit topic is created
    atomically in the same factory call.

    NOTE: differs from hedera/token.py which returned only token_id.
    The caller (lifecycle.py) receives both values now.
    """
    w3       = get_web3()
    settings = get_settings()
    factory  = _get_factory()
    operator = get_operator_address()
    pk       = get_operator_private_key()

    tx = factory.functions.deployAsset(
        name,
        symbol,
        initial_supply,
        decimals,
        asset_type,
        jurisdiction,
    ).build_transaction({
        "chainId":  settings.chain_id,
        "from":     Web3.to_checksum_address(operator),
        "nonce":    next_nonce(w3, operator),
        "gas":      4_000_000,
        "gasPrice": w3.eth.gas_price,
    })

    tx_hash = build_and_send(w3, tx, pk)

    # Read token address and topic from the AssetDeployed event
    receipt = w3.eth.get_transaction_receipt(tx_hash)
    factory_contract = _get_factory()
    events = factory_contract.events.AssetDeployed().process_receipt(receipt)

    if not events:
        raise RuntimeError(f"AssetDeployed event not found in receipt {tx_hash}")

    evt          = events[0]["args"]
    token_address = evt["tokenAddress"]
    topic_id      = evt["topicId"].hex()  # bytes32 → hex string

    logger.info(f"Deployed token {symbol} → {token_address}  topic={topic_id}")
    return token_address, topic_id


